<script>
    // Gallery JavaScript - OPTIMIZED & FIXED VERSION
    document.addEventListener('DOMContentLoaded', function() {
        // Initialize variables
        let currentGalleryImages = [];
        let currentIndex = 0;

        // Get all gallery items
        const galleryItems = document.querySelectorAll('.gallery-item');
        const lightboxModal = document.getElementById('lightboxModal');
        const lightboxImage = document.getElementById('lightboxImage');
        const lightboxTitle = document.getElementById('lightboxTitle');
        const lightboxDescription = document.getElementById('lightboxDescription');
        const lightboxCounter = document.getElementById('lightboxCounter');
        const closeLightbox = document.getElementById('closeLightbox');
        const prevButton = document.getElementById('prevImage');
        const nextButton = document.getElementById('nextImage');

        // Function to collect images from current tab
        function collectCurrentTabImages() {
            const activeTab = document.querySelector('.tab-pane.active');
            if (!activeTab) return [];

            const imageElements = activeTab.querySelectorAll('.gallery-item img');
            currentGalleryImages = Array.from(imageElements);
            console.log('Collected images:', currentGalleryImages.length);
            return currentGalleryImages;
        }

        // Open lightbox function - ADDED MISSING FUNCTION
        function openLightbox(clickedImage) {
            console.log('Opening lightbox for image:', clickedImage.src);

            // Collect images from current tab
            collectCurrentTabImages();

            if (currentGalleryImages.length === 0) {
                console.error('No images found in current tab');
                return;
            }

            // Find the index of clicked image
            currentIndex = currentGalleryImages.findIndex(img => {
                return img.src === clickedImage.src || img === clickedImage;
            });

            // If not found, default to first image
            if (currentIndex === -1) {
                currentIndex = 0;
                console.log('Image not found in collection, defaulting to first');
            }

            console.log('Current index:', currentIndex);

            // Update lightbox content
            updateLightboxContent();

            // Show lightbox
            lightboxModal.classList.add('active');
            document.body.style.overflow = 'hidden';

            // Add keyboard navigation
            document.addEventListener('keydown', handleKeyboardNavigation);
        }

        // Update lightbox content - SINGLE FUNCTION (removed duplicate)
        function updateLightboxContent() {
            if (currentGalleryImages.length === 0 || currentIndex < 0 || currentIndex >= currentGalleryImages
                .length) {
                console.error('Invalid image index or no images available');
                return;
            }

            const currentImage = currentGalleryImages[currentIndex];
            const parentItem = currentImage.closest('.gallery-item');

            // Reset image styles
            lightboxImage.style.cssText = `
            max-width: 100%;
            max-height: 70vh;
            width: auto;
            height: auto;
            object-fit: contain;
            display: block;
            margin: 0 auto;
            position: relative;
            top: 50%;
        `;

            // Set image with loading handler
            lightboxImage.onload = function() {
                console.log('Lightbox image loaded successfully');
            };

            lightboxImage.onerror = function() {
                console.error('Failed to load lightbox image');
                // Show placeholder if image fails to load
                this.src =
                    'data:image/svg+xml;utf8,<svg xmlns="http://www.w3.org/2000/svg" width="800" height="600" viewBox="0 0 800 600"><rect width="800" height="600" fill="%231F1F1F"/><text x="400" y="300" font-family="Arial" font-size="24" fill="%2363AF31" text-anchor="middle">Image not available</text></svg>';
                this.alt = 'Image failed to load';
            };

            // Set image source
            lightboxImage.src = currentImage.src;
            lightboxImage.alt = currentImage.alt || 'Gallery Image';

            // Set title and description from data attributes
            const title = currentImage.getAttribute('data-title') ||
                parentItem?.querySelector('.gallery-info h5')?.textContent ||
                'Gallery Image';
            const description = currentImage.getAttribute('data-description') ||
                parentItem?.querySelector('.gallery-info p')?.textContent ||
                '';

            lightboxTitle.textContent = title;
            lightboxDescription.textContent = description;

            // Update counter
            lightboxCounter.textContent = `${currentIndex + 1} / ${currentGalleryImages.length}`;
        }

        // Close lightbox function
        function closeLightboxFunc() {
            lightboxModal.classList.remove('active');
            document.body.style.overflow = 'auto';
            document.removeEventListener('keydown', handleKeyboardNavigation);
        }

        // Navigate to previous image
        function prevImage() {
            if (currentGalleryImages.length === 0) return;

            currentIndex = (currentIndex - 1 + currentGalleryImages.length) % currentGalleryImages.length;
            preloadLightboxImages();
            updateLightboxContent();
        }

        // Navigate to next image
        function nextImage() {
            if (currentGalleryImages.length === 0) return;

            currentIndex = (currentIndex + 1) % currentGalleryImages.length;
            preloadLightboxImages();
            updateLightboxContent();
        }

        // Keyboard navigation handler
        function handleKeyboardNavigation(e) {
            switch (e.key) {
                case 'Escape':
                    closeLightboxFunc();
                    break;
                case 'ArrowLeft':
                    prevImage();
                    break;
                case 'ArrowRight':
                    nextImage();
                    break;
            }
        }

        // Add this function to preload images for better performance
        function preloadLightboxImages() {
            if (currentGalleryImages.length === 0) return;

            // Preload current, next, and previous images
            const indicesToPreload = [
                currentIndex,
                (currentIndex + 1) % currentGalleryImages.length,
                (currentIndex - 1 + currentGalleryImages.length) % currentGalleryImages.length
            ];

            indicesToPreload.forEach(index => {
                if (index >= 0 && index < currentGalleryImages.length) {
                    const img = new Image();
                    img.src = currentGalleryImages[index].src;
                }
            });
        }

        // Add click event to all gallery items
        galleryItems.forEach(item => {
            const image = item.querySelector('img');
            const expandButton = item.querySelector('.gallery-expand');

            // Store original image reference
            const originalImage = image;

            // Create a copy of image data for reliable comparison
            item.dataset.imageSrc = image.src;
            item.dataset.imageAlt = image.alt;

            // Click on image opens lightbox
            image.addEventListener('click', function(e) {
                e.stopPropagation();
                openLightbox(originalImage);
            });

            // Click on item container (excluding expand button)
            item.addEventListener('click', function(e) {
                // Don't trigger if clicking on expand button or image (already handled)
                if (e.target === expandButton || e.target === image || e.target.closest(
                        '.gallery-expand')) {
                    return;
                }
                openLightbox(originalImage);
            });

            // Expand button also opens lightbox
            if (expandButton) {
                expandButton.addEventListener('click', function(e) {
                    e.stopPropagation();
                    e.preventDefault();
                    openLightbox(originalImage);
                });
            }
        });

        // Lightbox controls
        closeLightbox.addEventListener('click', closeLightboxFunc);
        prevButton.addEventListener('click', prevImage);
        nextButton.addEventListener('click', nextImage);

        // Close lightbox when clicking outside image
        lightboxModal.addEventListener('click', function(e) {
            if (e.target === lightboxModal || e.target.classList.contains('lightbox-close')) {
                closeLightboxFunc();
            }
        });

        // Tab change handler - reset current images
        document.querySelectorAll('[data-bs-toggle="pill"]').forEach(tab => {
            tab.addEventListener('shown.bs.tab', function() {
                console.log('Tab changed, collecting new images');
                collectCurrentTabImages();
                // Reset index when tab changes
                currentIndex = 0;
            });
        });

        // Fix image loading issues
        function fixImageLoading() {
            const images = document.querySelectorAll('.gallery-item img');
            images.forEach(img => {
                // Remove problematic CSS loading background
                img.style.background = 'none';
                img.style.animation = 'none';

                // Add error handling for gallery images
                img.onerror = function() {
                    console.error('Gallery image failed to load:', this.src);
                    // Replace with placeholder
                    this.src =
                        'data:image/svg+xml;utf8,<svg xmlns="http://www.w3.org/2000/svg" width="400" height="300" viewBox="0 0 400 300"><rect width="400" height="300" fill="%231F1F1F"/><text x="200" y="150" font-family="Arial" font-size="16" fill="%2363AF31" text-anchor="middle">Trading Platform</text></svg>';
                    this.alt = 'Image preview';
                };

                // Handle successful load
                img.onload = function() {
                    this.style.opacity = '1';
                };
            });
        }

        // Initialize
        function initializeGallery() {
            collectCurrentTabImages();
            console.log('Initialized with', currentGalleryImages.length, 'images');
            fixImageLoading();
            preloadLightboxImages();
        }

        // Add smooth scroll to gallery section
        const galleryLinks = document.querySelectorAll('a[href="#gallery"]');
        galleryLinks.forEach(link => {
            link.addEventListener('click', function(e) {
                e.preventDefault();
                document.querySelector('#gallery').scrollIntoView({
                    behavior: 'smooth',
                    block: 'start'
                });
            });
        });

        // Initialize gallery
        initializeGallery();

        // Debug helper function
        window.debugGallery = function() {
            console.log('Current gallery state:');
            console.log('- Total images:', currentGalleryImages.length);
            console.log('- Current index:', currentIndex);
            console.log('- Active tab:', document.querySelector('.tab-pane.active')?.id);

            currentGalleryImages.forEach((img, idx) => {
                console.log(`  [${idx}] ${img.src.substring(0, 50)}...`);
            });
        };
    });
</script>
