<script>
    // Services Page JavaScript - Trading Education Focus
    document.addEventListener('DOMContentLoaded', function() {
        // Service card interactions
        const serviceCards = document.querySelectorAll('.service-card');
        serviceCards.forEach(card => {
            // Add hover effects
            card.addEventListener('mouseenter', function() {
                const icon = this.querySelector('.service-icon');
                if (icon) {
                    icon.style.transform = 'scale(1.1) rotate(5deg)';
                    icon.style.transition = 'transform 0.3s ease';
                }

                // Pulse effect for featured card
                if (this.classList.contains('feature-card')) {
                    this.style.boxShadow = '0 20px 50px rgba(99, 175, 49, 0.3)';
                }
            });

            card.addEventListener('mouseleave', function() {
                const icon = this.querySelector('.service-icon');
                if (icon) {
                    icon.style.transform = 'scale(1) rotate(0)';
                }

                if (this.classList.contains('feature-card')) {
                    this.style.boxShadow = '0 15px 40px rgba(99, 175, 49, 0.2)';
                }
            });

            // Enroll button click effect
            const enrollBtn = card.querySelector('.btn-primary');
            if (enrollBtn) {
                enrollBtn.addEventListener('click', function(e) {
                    e.stopPropagation();
                    const serviceName = card.querySelector('h3').textContent;
                    const servicePrice = card.querySelector('.price').textContent;

                    // Show enrollment modal or confirmation
                    showEnrollmentModal(serviceName, servicePrice);

                    // Button animation
                    this.style.transform = 'scale(0.95)';
                    setTimeout(() => {
                        this.style.transform = 'scale(1)';
                    }, 150);
                });
            }
        });

        // Learning path step animations
        const pathSteps = document.querySelectorAll('.path-step');
        pathSteps.forEach((step, index) => {
            // Initial animation
            setTimeout(() => {
                step.style.opacity = '1';
                step.style.transform = 'translateX(0)';
            }, index * 200);
        });

        // Methodology step animations
        const methodologySteps = document.querySelectorAll('.step');
        methodologySteps.forEach((step, index) => {
            step.style.opacity = '0';
            step.style.transform = 'translateY(20px)';
            step.style.transition = 'opacity 0.5s ease, transform 0.5s ease';

            setTimeout(() => {
                step.style.opacity = '1';
                step.style.transform = 'translateY(0)';
            }, index * 300);
        });

        // Testimonial animations
        const testimonialCards = document.querySelectorAll('.testimonial-card');
        testimonialCards.forEach((card, index) => {
            card.style.opacity = '0';
            card.style.transform = 'translateY(20px)';
            card.style.transition = 'opacity 0.5s ease, transform 0.5s ease';

            setTimeout(() => {
                card.style.opacity = '1';
                card.style.transform = 'translateY(0)';
            }, index * 200);
        });

        // FAQ accordion enhancements
        const accordionButtons = document.querySelectorAll('.accordion-button');
        accordionButtons.forEach(button => {
            button.addEventListener('click', function() {
                const icon = this.querySelector('.accordion-icon');
                if (!icon) {
                    // Add custom icon if not present
                    const icon = document.createElement('i');
                    icon.className = 'accordion-icon fas fa-chevron-down ms-2';
                    this.appendChild(icon);
                }

                // Rotate icon
                const icon = this.querySelector('.accordion-icon');
                if (icon) {
                    if (this.classList.contains('collapsed')) {
                        icon.style.transform = 'rotate(0deg)';
                    } else {
                        icon.style.transform = 'rotate(180deg)';
                    }
                    icon.style.transition = 'transform 0.3s ease';
                }
            });
        });

        // Free Zone and VIP enrollment
        const freeZoneBtn = document.querySelector('.free-zone .btn');
        if (freeZoneBtn) {
            freeZoneBtn.addEventListener('click', function() {
                showFreeZoneModal();
            });
        }

        const vipSubscribeBtn = document.querySelector('.vip-telegram .btn-primary');
        if (vipSubscribeBtn) {
            vipSubscribeBtn.addEventListener('click', function() {
                showVIPModal();
            });
        }

        // Final CTA buttons
        const ctaButtons = document.querySelectorAll('.final-cta .btn');
        ctaButtons.forEach(btn => {
            btn.addEventListener('click', function() {
                if (this.textContent.includes('Free Trial')) {
                    showFreeTrialModal();
                } else {
                    showConsultationModal();
                }
            });
        });

        // Animation on scroll
        const observerOptions = {
            threshold: 0.2,
            rootMargin: '0px 0px -100px 0px'
        };

        const observer = new IntersectionObserver((entries) => {
            entries.forEach(entry => {
                if (entry.isIntersecting) {
                    entry.target.classList.add('animated');
                }
            });
        }, observerOptions);

        // Observe sections
        document.querySelectorAll('.service-card, .special-service-card, .testimonial-card').forEach(el => {
            observer.observe(el);
        });

        // Helper functions for modals (to be implemented)
        function showEnrollmentModal(serviceName, price) {
            alert(
                `Enrollment for ${serviceName} at ${price} will begin shortly. This feature will be connected to your payment system.`);
        }

        function showFreeZoneModal() {
            alert('Welcome to Free Trade Zone! You will be redirected to our free resources section.');
        }

        function showVIPModal() {
            alert('VIP Telegram Subscription - You will be redirected to the payment and setup process.');
        }

        function showFreeTrialModal() {
            alert('Free Trial Started! You now have 7-day access to our basic trading course.');
        }

        function showConsultationModal() {
            alert('Consultation booking modal will appear here with calendar integration.');
        }
    });
</script>
